"""Copy the planter CAD meshes from the assembly viewer into the website.

Source: ggpcb3/planter/renders/assembly_viewer.html (built by planter/source/build_viewer.py).
Output: assets/model-data.js, which defines window.MESHES and window.META.
Re-run after the CAD changes:  python3 tools/export_model.py
"""
import re, sys
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else
           Path.home() / "Desktop/ggpcb3/planter/renders/assembly_viewer.html")
OUT = Path(__file__).resolve().parent.parent / "assets" / "model-data.js"

html = SRC.read_text()
meshes = re.search(r"window\.MESHES=(\{.*?\});\n", html, re.S).group(1)
meta = re.search(r"window\.META=(\{.*?\});\n", html, re.S).group(1)
OUT.write_text(f"/* Generated by tools/export_model.py from {SRC.name}. Do not edit. */\n"
               f"window.MESHES={meshes};\nwindow.META={meta};\n")
print(f"wrote {OUT} ({OUT.stat().st_size/1e6:.2f} MB)")
